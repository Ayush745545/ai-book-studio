import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import ts from 'typescript';
const require = createRequire(import.meta.url), exports = {}, accounts = new Map();
const env = { NEXTAUTH_SECRET: 'local-test-secret-for-encryption-checks-only' };
const source = fs.readFileSync(new URL('../src/lib/ai-credentials.ts', import.meta.url), 'utf8');
const compiled = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
vm.runInNewContext(compiled, { exports, Buffer, process: { env }, require(name) { if (name === '@/lib/prisma') return { prisma: { user: { findUnique: async ({where}) => accounts.get(where.id) ?? null } } }; return require(name); } });
const key = 'sk-or-v1-fixture-for-encryption-unit-tests', encrypted = exports.encryptApiKey(key);
assert.equal(exports.decryptApiKey(encrypted), key);
assert.ok(!encrypted.includes(key));
assert.notEqual(exports.encryptApiKey(key), encrypted, 'Every encryption uses a fresh nonce');
const tampered = encrypted.split('.');
const ciphertext = Buffer.from(tampered[2], 'base64'); ciphertext[0] ^= 1; tampered[2] = ciphertext.toString('base64');
assert.throws(() => exports.decryptApiKey(tampered.join('.')), 'Tampered ciphertext is rejected');
accounts.set('author-a', { openRouterKey: encrypted });
accounts.set('author-b', { openRouterKey: exports.encryptApiKey('sk-or-v1-another-author-fixture') });
assert.equal((await exports.writingCredentials('author-a')).apiKey, key);
assert.equal((await exports.writingCredentials('author-b')).apiKey, 'sk-or-v1-another-author-fixture');
await assert.rejects(exports.writingCredentials('author-c'), /Connect OpenRouter/);
env.OPENROUTER_API_KEY = 'sk-or-v1-server-fixture';
assert.equal((await exports.writingCredentials('author-c')).apiKey, env.OPENROUTER_API_KEY);
assert.equal((await exports.writingCredentials('author-a')).apiKey, key, 'A personal key takes precedence over the server key');
console.log('9 AI connection checks passed: encryption, tamper detection, account isolation, and key fallback.');
