import { chromium, expect } from '@playwright/test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
const base = process.env.BASE_URL || 'http://127.0.0.1:3001';
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const created = [];
let checks = 0;
const check = (condition, description) => { assert.ok(condition, description); checks++; console.log(`PASS ${description}`); };
try {
  await fs.mkdir('.local/qa', { recursive: true });
  await page.goto(base);
  await page.getByRole('tab', { name: /Write/ }).click();
  await expect(page.getByRole('tabpanel')).toContainText('Stay with the thought');
  await page.getByRole('tab', { name: /Write/ }).press('ArrowRight');
  await expect(page.getByRole('tabpanel')).toContainText('Make something ready to be read');
  check(true, 'Homepage tour responds to click and keyboard');
  await page.getByRole('button', { name: 'Pause motion' }).click();
  check(await page.locator('.studio-book-object').evaluate(el => getComputedStyle(el).animationPlayState) === 'paused', 'Motion pause control stops animation');
  await page.locator('summary').filter({ hasText: 'Can I write without AI?' }).click();
  await expect(page.locator('details[open]')).toContainText('The editor, autosave');
  check(true, 'FAQ opens a real answer');
  // Reveal each section before taking a full-page image.
  for (const section of await page.locator('[data-reveal]').all()) await section.scrollIntoViewIfNeeded();
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.screenshot({ path: '.local/qa/home-enhanced-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(base);
  for (const section of await page.locator('[data-reveal]').all()) await section.scrollIntoViewIfNeeded();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Homepage fits a phone without sideways scrolling');
  await page.getByRole('tab', { name: /Export/ }).click();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Export illustration fits on a phone');
  await page.evaluate(() => window.scrollTo({ top: 0, behavior: 'instant' }));
  await page.screenshot({ path: '.local/qa/home-enhanced-mobile.png', fullPage: true });
  await page.emulateMedia({ reducedMotion: 'reduce' });
  check(await page.locator('.studio-book-object').evaluate(el => getComputedStyle(el).animationName) === 'none', 'Reduced motion preference disables decorative motion');
  await page.emulateMedia({ reducedMotion: 'no-preference' });
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(`${base}/login`);
  await page.getByLabel('Email address').fill(`studio-ui-${Date.now()}@example.com`);
  await page.getByLabel('Password', { exact: true }).fill('Studio-ui-test-8472');
  await page.getByRole('button', { name: 'Continue to my studio' }).click();
  await page.waitForURL(/dashboard/);
  for (const title of ['A project to keep', 'A project to delete']) {
    const res = await context.request.post(`${base}/api/books`, { data: { title, format: 'book', outline: ['First chapter'] } });
    assert.equal(res.status(), 201);
    const { book } = await res.json(); created.push(book.id);
    const saved = await context.request.put(`${base}/api/chapters/${book.chapters[0].id}`, { data: { content: 'A small beginning for a meaningful book.' } });
    assert.equal(saved.status(), 200);
  }
  await page.goto(`${base}/dashboard`);
  await page.getByRole('heading', { name: 'Your writing activity' }).waitFor();
  await expect(page.locator('.studio-activity-heading p')).toContainText('2 saved');
  const stats = await page.locator('.studio-dashboard-stats').boundingBox();
  const calendar = await page.locator('.studio-activity').boundingBox();
  check(stats.height < 90 && calendar.height < 340, `Compact stats (${Math.round(stats.height)}px) and calendar (${Math.round(calendar.height)}px)`);
  check(await page.locator('#writing-day-detail').isHidden(), 'Day details are collapsed by default');
  await page.getByRole('button', { name: 'View daily details +' }).click();
  await expect(page.locator('#writing-day-detail')).toBeVisible();
  await page.getByRole('button', { name: 'Hide daily details −' }).click();
  await page.getByRole('button', { name: 'Delete A project to delete', exact: true }).click();
  await expect(page.getByRole('alertdialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(page.getByRole('alertdialog')).toHaveCount(0);
  check(await page.getByRole('button', { name: 'Delete A project to delete', exact: true }).evaluate(el => el === document.activeElement), 'Cancel restores focus to delete control');
  await page.getByRole('button', { name: 'Delete A project to delete', exact: true }).click();
  await page.getByRole('button', { name: 'Keep project', exact: true }).click();
  check((await context.request.get(`${base}/api/books/${created[1]}`)).ok(), 'Cancel keeps the project');
  const target = `${base}/api/books/${created[1]}`;
  await page.route(target, async route => {
    if (route.request().method() === 'DELETE') await route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'Temporary deletion failure. Try again.' }) });
    else await route.continue();
  });
  await page.getByRole('button', { name: 'Delete A project to delete', exact: true }).click();
  await page.getByRole('button', { name: 'Delete project', exact: true }).click();
  await expect(page.getByRole('alertdialog').getByRole('alert')).toContainText('Temporary deletion failure');
  check(await page.getByRole('alertdialog').isVisible(), 'Failed delete preserves dialog and displays error');
  await page.unroute(target);
  await page.getByRole('button', { name: 'Delete project', exact: true }).click();
  await expect(page.getByRole('alertdialog')).toHaveCount(0);
  await expect(page.getByRole('button', { name: 'Delete A project to delete', exact: true })).toHaveCount(0);
  await expect(page.locator('.studio-dashboard-stats > div').first()).toContainText('1');
  check((await context.request.get(target)).status() === 404, 'Confirmed deletion removes project on server and refreshes totals');
  check((await context.request.get(`${base}/api/books/${created[0]}`)).ok(), 'Other projects are preserved');
  const activity = await (await context.request.get(`${base}/api/activity`)).json();
  check(activity.days.reduce((sum, day) => sum + day.edits, 0) === 2, 'Writing history survives project deletion');
  await page.reload();
  await expect(page.getByRole('button', { name: 'Delete A project to delete', exact: true })).toHaveCount(0);
  check(true, 'Deleted project stays removed after reload');
  await page.screenshot({ path: '.local/qa/dashboard-compact-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.goto(`${base}/dashboard`);
  await expect(page.getByRole('button', { name: 'Delete A project to keep', exact: true })).toBeVisible();
  check(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Compact dashboard fits phone; delete is visible');
  await page.screenshot({ path: '.local/qa/dashboard-compact-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Delete A project to keep', exact: true }).click();
  await page.screenshot({ path: '.local/qa/delete-confirmation-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Keep project', exact: true }).click();
  const visitor = await browser.newContext();
  check((await visitor.request.delete(`${base}/api/books/${created[0]}`)).status() === 401, 'Unauthenticated deletion is rejected');
  await visitor.close();
  check(errors.length === 0, `No browser errors: ${errors.join('; ')}`);
  console.log(`Completed ${checks} UI checks.`);
} finally {
  for (const id of created) await context.request.delete(`${base}/api/books/${id}`).catch(() => {});
  await browser.close();
}
